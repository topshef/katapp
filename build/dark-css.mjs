// build/dark-css.mjs — DARK-PAGES1 (owner 2026-11-10: "please do all the other pages too for dark mode")
//
// Katomia's pages were written light-only. Without a dark theme Chrome's "darken websites" repaints
// them by its own algorithm (muddy, and it flips some layers the wrong way: see DARK-VEIL1 in
// katomia-board.js). The board got a hand-written dark mode (katomia-board.css DARK-BOARD1); the
// other pages share katomia.css plus one <style> block each, a few thousand lines of light colours.
// Hand-writing a twin for each would take a day and go stale the first time someone edits a page.
//
// So this script writes the twins: it reads each light stylesheet through Chromium's own CSS
// parser (no hand-rolled parsing), and for every rule that sets a colour it emits the same
// selector inside @media (prefers-color-scheme: dark) with the colour mapped in OKLCH, so hues
// survive: pale surfaces become dark surfaces (a white card stays a step above the page, as
// elevation reads in dark UIs), dark text becomes light text of the same hue, light borders
// become dark borders, black hairlines become white hairlines, saturated accents stay.
//
// Where the twins go, and why there (the cascade must come out the same as in light):
//   katomia.css          → katomia-dark.css, linked RIGHT AFTER katomia.css on each page, so a
//                          page's own <style> (light and dark) still overrides it as before.
//   a page's <style>     → a generated <style> block right after it (between DARK-PAGES1 markers).
// Hand fixes live OUTSIDE the generated regions (katomia-dark.css below its marker; a page's own
// "DARK-PAGES1 hand" block) and survive a re-run.
// A selector+property that already has a hand-written dark rule in the same file is skipped.
// The board (board.php) does not load katomia-dark.css: it has its own dark mode.
//
// Re-run after editing a page's light colours:  node build/dark-css.mjs   (then build-static.sh)
// It needs Chromium (Playwright from qa/board): cd qa/board && npm ci, once.

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from '../qa/board/node_modules/playwright/index.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const K = join(ROOT, 'public_html/m/katomia')
const PAGES = ['landing.php', 'circles.php', 'contents.php', 'learn.php', 'advisor.php', 'host.php',
  'create-game.php', 'binding.php',
  'header.php',   // the shared banner + menu: included by every page, the board too (its own dark rules out-rank these)
  '../../future/index_v2.php',   // /m/sign's own block (its chrome's twins are future-dark.css)
  '../../cookieConsent.php']      // the cookie notice, shown on first visit by every page that includes it
// CSS that a script injects at run time (later than katomia-dark.css, so the twins are written with a
// :root prefix to out-rank the light rules at equal specificity; the order among twins is unchanged)
const JS_CSS = [
  ['katomia-composer.js', s => /const CSS = `([\s\S]*?)`/.exec(s)?.[1]],
  ['kchanges.js', s => { const a = s.indexOf('s.textContent ='); if (a < 0) return null
    const stmt = s.slice(a, s.indexOf('";\n', a) + 2)
    return [...stmt.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(m => JSON.parse('"' + m[1] + '"')).join('') }],
]
const GEN_START = '/* ═══ DARK-PAGES1 generated by build/dark-css.mjs — do not edit inside; re-run it ═══ */'
const GEN_END = '/* ═══ end of generated ═══ */'
const PAGE_START = '<!-- DARK-PAGES1 generated by build/dark-css.mjs from the <style> above — do not edit; re-run it -->'
const PAGE_END = '<!-- /DARK-PAGES1 generated -->'

const browser = await chromium.launch()
const page = await browser.newPage()

// twins for one stylesheet's text → CSS text (rules only, no outer @media)
async function twins(css, prefix = '', keepAll = false) {
  return page.evaluate(([css, prefix, keepAll]) => {
    // ── colour maths (OKLab, Björn Ottosson) ──
    const lin = c => { c /= 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4 }
    const gam = c => { const v = c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055; return Math.round(Math.max(0, Math.min(1, v)) * 255) }
    const toLab = (r, g, b) => {
      r = lin(r); g = lin(g); b = lin(b)
      const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
      const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
      const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
      const L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s
      const A = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s
      const B = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
      return { L, C: Math.hypot(A, B), h: Math.atan2(B, A) }
    }
    const fromLab = ({ L, C, h }) => {
      const A = C * Math.cos(h), B = C * Math.sin(h)
      const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3
      const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3
      const s = (L - 0.0894841775 * A - 1.2914855480 * B) ** 3
      return [gam(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
              gam(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
              gam(-0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s)]
    }
    const probe = document.createElement('i'); document.body.appendChild(probe)
    const parse = tok => {   // any CSS colour → [r,g,b,a] via the browser, or null
      probe.style.color = ''; probe.style.color = tok
      if (!probe.style.color) return null
      const m = /rgba?\(([^)]+)\)/.exec(getComputedStyle(probe).color); if (!m) return null
      const p = m[1].split(',').map(Number); return [p[0], p[1], p[2], p.length > 3 ? p[3] : 1]
    }
    const out = (rgb, a) => a >= 1 ? `rgb(${rgb[0]}, ${rgb[1]}, ${rgb[2]})` : `rgba(${rgb[0]}, ${rgb[1]}, ${rgb[2]}, ${+a.toFixed(3)})`
    const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v))

    // the page sits at #f5f5f5 / #f7f9fc (L ≈ .97) → ≈ #16181c (L ≈ .205); a white card (L 1) a step up
    const PAGE_L = 0.969, DARK_PAGE_L = 0.205
    // a translucent mid-grey (KEA's rgba(128,128,128,.25)) reads the same on light and dark: keep it
    const neutral = (c, a) => a < 1 && c.C < 0.02 && c.L > 0.4 && c.L < 0.8
    function mapBg([r, g, b, a]) {
      if (a === 0) return null
      const c = toLab(r, g, b)
      if (neutral(c, a)) return null
      if (a < 1 && c.L > 0.85) return out(fromLab({ L: 0.24, C: Math.min(c.C, 0.02), h: c.h }), clamp(a * 1.1, 0, 1))  // white glass → dark glass
      if (a <= 0.15 && c.L < 0.35) return out([255, 255, 255], +(a * 0.9).toFixed(3))   // a faint black wash (hover tint) → white wash
      if (a < 1 && c.L < 0.35) return null                                                 // a scrim/backdrop stays dark
      // pale surfaces: keep their order (a white card a step above the #f5f5f5 page, a grey
      // hover a step below), compressed into the dark band; floor so greys never go black
      if (c.L >= 0.85) {
        const L = clamp(DARK_PAGE_L + (c.L - PAGE_L) * 0.9, 0.15, 0.30)
        return out(fromLab({ L, C: Math.min(c.C * 1.1, 0.045), h: c.h }), a)
      }
      // mid-light greys and tints (rare as fills): just above the floor, continuous at .85
      if (c.L >= 0.6 && c.C < 0.12) {
        const L = 0.15 + (0.85 - c.L) * 0.6
        return out(fromLab({ L, C: Math.min(c.C, 0.06), h: c.h }), a)
      }
      return null   // saturated accents and dark surfaces stay
    }
    function mapFg([r, g, b, a]) {
      if (a === 0) return null
      const c = toLab(r, g, b)
      if (neutral(c, a)) return null
      if (c.L > 0.62) return null
      // dark text → light text, same hue: black → .96, #333 → .84, #666 → .77; coloured text kept
      // in a band where it still reads as its colour
      const L = c.C > 0.05 ? clamp(0.96 - c.L * 0.38, 0.74, 0.85) : 0.96 - c.L * 0.38
      return out(fromLab({ L, C: Math.min(c.C, 0.16), h: c.h }), a)
    }
    function mapBorder([r, g, b, a]) {
      if (a === 0) return null
      const c = toLab(r, g, b)
      if (neutral(c, a)) return null
      if (c.C > 0.1 && c.L < 0.9) return null   // a saturated accent border (an orange ready ring) stays
      if (a < 1 && c.L < 0.4) return out([255, 255, 255], +(a * 0.9).toFixed(3))
      if (a < 1 && c.L > 0.85) return out([255, 255, 255], +(a * 0.18).toFixed(3))
      if (c.C > 0.08 && c.L < 0.8) return null
      if (c.L >= 0.75) return out(fromLab({ L: 0.30 + (c.L - 0.75) * 0.3, C: Math.min(c.C, 0.04), h: c.h }), a)
      if (c.L >= 0.45) return out(fromLab({ L: 0.36 + (0.75 - c.L) * 0.2, C: Math.min(c.C, 0.04), h: c.h }), a)
      return out(fromLab({ L: 0.55, C: Math.min(c.C, 0.06), h: c.h }), a)
    }
    function mapShadow([r, g, b, a]) {
      const c = toLab(r, g, b)
      if (c.L > 0.8) return out([255, 255, 255], +(a * 0.15).toFixed(3))
      return null
    }
    const TOK = /rgba?\([^)]*\)|hsla?\([^)]*\)|#[0-9a-fA-F]{3,8}\b|\b(?:white|black|gray|grey|silver|whitesmoke|gainsboro|lightgr[ae]y|darkgr[ae]y|dimgr[ae]y|ghostwhite|snow|ivory|linen|beige|aliceblue|azure|honeydew|mintcream|floralwhite|oldlace|seashell|lavender|lavenderblush|mistyrose|cornsilk|lemonchiffon|papayawhip|blanchedalmond|bisque|antiquewhite|wheat)\b/g
    const mapValue = (v, fn) => {
      let changed = false
      const nv = v.replace(TOK, tok => { const rgba = parse(tok); if (!rgba) return tok; const m = fn(rgba); if (m == null) return tok; changed = true; return m })
      return changed ? nv : null
    }
    // custom properties that hold a colour get a twin too; their role is read from the name
    const ROLE = p =>
      /^--/.test(p) ? (/line|border|rule|edge|hair|sep|stroke/i.test(p) ? mapBorder
        : /ink|text|fg|muted|label|link/i.test(p) ? mapFg
        : /bg|back|surface|card|paper|panel|wash|fill|tint|felt|shade/i.test(p) ? mapBg : null) :
      /^background-color$|^background-image$/.test(p) ? mapBg :
      /^(color|fill|stroke|caret-color|text-decoration-color|-webkit-text-fill-color|text-emphasis-color)$/.test(p) ? mapFg :
      /^(border-(top|right|bottom|left|block-start|block-end|inline-start|inline-end)-color|outline-color|column-rule-color)$/.test(p) ? mapBorder :
      /^(box-shadow|text-shadow)$/.test(p) ? mapShadow : null

    const st = document.createElement('style'); st.textContent = css; document.head.appendChild(st)
    const sheet = st.sheet
    // selector+property pairs a hand-written dark rule already sets — no twin for those
    const hand = new Set()
    const isDark = r => r instanceof CSSMediaRule && /prefers-color-scheme:\s*dark/.test(r.conditionText || r.media.mediaText)
    const collectHand = rules => { for (const r of rules) {
      if (r instanceof CSSStyleRule) for (let i = 0; i < r.style.length; i++) hand.add(r.selectorText + '|' + r.style[i])
      else if (r.cssRules) collectHand(r.cssRules) } }
    const findHand = rules => { for (const r of rules) { if (isDark(r)) collectHand(r.cssRules); else if (r.cssRules) findHand(r.cssRules) } }
    findHand(sheet.cssRules)

    const lines = []
    let count = 0
    const walk = (rules, wrap) => {
      for (const r of rules) {
        if (isDark(r)) continue
        if (r instanceof CSSMediaRule) { if (/prefers-color-scheme/.test(r.media.mediaText)) continue; walk(r.cssRules, [...wrap, '@media ' + r.media.mediaText]); continue }
        if (r instanceof CSSSupportsRule) { walk(r.cssRules, [...wrap, '@supports ' + r.conditionText]); continue }
        if (!(r instanceof CSSStyleRule)) continue
        const decls = []
        for (let i = 0; i < r.style.length; i++) {
          const p = r.style[i], fn = ROLE(p); if (!fn) continue
          if (hand.has(r.selectorText + '|' + p)) continue
          // a colour inside var(--x, <fallback>) is mapped too (it only shows when --x is unset)
          const v = r.style.getPropertyValue(p).trim(); if (!v || /^(inherit|currentcolor|initial|unset|revert)$/i.test(v)) continue
          // keepAll: an unchanged colour is re-stated too, so a LATER sheet's light colour still beats an
          // earlier sheet's dark twin when both share one twin file (the cascade order of the originals)
          let nv = mapValue(v, fn); if (nv == null) { if (!keepAll || !/rgb|#|hsl|white|black/i.test(v)) continue; nv = v }
          decls.push(`${p}: ${nv}${r.style.getPropertyPriority(p) ? ' !important' : ''}`)
        }
        // a prefix goes on each selector of the list (split on top-level commas only)
        const selText = !prefix ? r.selectorText : (() => { const parts = []; let d = 0, cur = ''
          for (const ch of r.selectorText) { if (ch === '(') d++; if (ch === ')') d--; if (ch === ',' && !d) { parts.push(cur); cur = '' } else cur += ch }
          parts.push(cur); return parts.map(x => prefix + x.trim()).join(', ') })()
        if (decls.length) { count++; lines.push(wrap.map(w => w + '{').join('') + `${selText}{ ${decls.join('; ')}; }` + '}'.repeat(wrap.length)) }
      }
    }
    walk(sheet.cssRules, [])
    st.remove(); probe.remove()
    return { text: lines.join('\n'), count }
  }, [css, prefix, keepAll])
}

// ── shared stylesheets → one twin file each (generated region; the hand section below the end
// marker stays). Each set's twin file is linked right AFTER the last of its sources.
const PUB = join(ROOT, 'public_html'), DIST = join(ROOT, 'build/dist')
const SETS = [
  { out: join(K, 'katomia-dark.css'), what: 'katomia.css (+ CSS that two scripts inject)',
    note: 'Linked right after katomia.css on every Katomia page except the board (katomia-board.css DARK-BOARD1 is its own).',
    sources: [{ name: 'katomia.css', css: () => readFileSync(join(K, 'katomia.css'), 'utf8') },
      ...JS_CSS.map(([f, pick]) => ({ name: f + ' (injected at run time)', prefix: ':root ', css: () => pick(readFileSync(join(K, f), 'utf8')) }))] },
  { out: join(K, 'KEA/kea-dark.css'), what: 'KEA/kea.css', note: 'Linked right after kea.css in KEA/app.html.',
    sources: [{ name: 'kea.css', css: () => readFileSync(join(K, 'KEA/kea.css'), 'utf8') }] },
  // /m/sign renders future/index.php inside the old site chrome: Bootstrap, the chrome stylesheet
  // (PHP: read from its rendered copy in build/dist, so run build-static.sh first), owl, future.css
  { out: join(PUB, 'future/future-dark.css'), what: 'the /m/sign chrome (bootstrap, style.php.css, owl.css, future.css)',
    note: 'Linked right after future.css by future/index.php. Later sheets restate their unchanged colours so they still win.',
    sources: [
      { name: 'vendor/bootstrap/css/bootstrap.min.css', css: () => readFileSync(join(PUB, 'vendor/bootstrap/css/bootstrap.min.css'), 'utf8') },
      { name: 'assets/css/style.php.css', keepAll: true, css: () => readFileSync(join(DIST, 'assets/css/style.php.css'), 'utf8') },
      { name: 'assets/css/owl.css', keepAll: true, css: () => readFileSync(join(PUB, 'assets/css/owl.css'), 'utf8') },
      { name: 'future/future.css', keepAll: true, css: () => readFileSync(join(PUB, 'future/future.css'), 'utf8') }] },
]
for (const set of SETS) {
  let text = '', count = 0
  for (const src of set.sources) {
    let css = null; try { css = src.css() } catch {}
    if (!css) { console.log(set.out, src.name, 'no CSS found'); continue }
    const t = await twins(css, src.prefix || '', !!src.keepAll)
    text += `\n/* from ${src.name} */\n` + t.text; count += t.count
  }
  let old = ''
  try { old = readFileSync(set.out, 'utf8') } catch {}
  const hand = old.includes(GEN_END) ? old.slice(old.indexOf(GEN_END) + GEN_END.length) : `

/* ═══ DARK-PAGES1 hand-tuned (below the generated twins, so these win) ═══ */
@media (prefers-color-scheme: dark){
}
`
  writeFileSync(set.out, `${GEN_START}
/* The dark twins of ${set.what}. ${set.note}
   How and why: build/dark-css.mjs */
@media (prefers-color-scheme: dark){${text}
}
${GEN_END}${hand}`)
  console.log(`${set.out.replace(ROOT + '/', '')}: ${count} rules`)
}

// ── each page's <style> → a generated block right after it
for (const f of PAGES) {
  const p = join(K, f)
  let s = readFileSync(p, 'utf8')
  const crlf = s.includes('\r\n')
  if (crlf) s = s.replace(/\r\n/g, '\n')
  // drop an earlier generated block
  const a = s.indexOf(PAGE_START)
  if (a >= 0) { const b = s.indexOf(PAGE_END, a); s = s.slice(0, a).replace(/\n$/, '') + s.slice(b + PAGE_END.length) }
  // the page's own block: a <style> tag that starts a line (not the words in a comment)
  const m = /(?<=^|\n)[ \t]*<style[^>]*>([\s\S]*?)<\/style>/.exec(s)
  if (!m) { console.log(f, 'no <style>'); continue }
  const t = await twins(m[1])
  const at = m.index + m[0].length
  const block = `\n${PAGE_START}\n<style>\n@media (prefers-color-scheme: dark){\n${t.text}\n}\n</style>\n${PAGE_END}`
  s = s.slice(0, at) + block + s.slice(at)
  if (crlf) s = s.replace(/\n/g, '\r\n')
  writeFileSync(p, s)
  console.log(`${f}: ${t.count} rules`)
}
await browser.close()
