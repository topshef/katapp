#!/bin/sh
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

cd "$PROJECT_ROOT" || exit 1

PACKAGE="package.json"
TARGET="src/__snapgate__.js"

if [ ! -f "$PACKAGE" ]; then
  echo "package.json not found."
  exit 1
fi

NAME=$(grep '"name"' "$PACKAGE" | head -1 | sed -E 's/.*"name": *"([^"]+)".*/\1/')
VERSION=$(grep '"version"' "$PACKAGE" | head -1 | sed -E 's/.*"version": *"([^"]+)".*/\1/')

HEAD_SHORT=$(git rev-parse --short HEAD)
HEAD_FULL=$(git rev-parse HEAD)
HEAD_DATE=$(git log -1 --format=%cd --date=short)
REPO=$(git config --get remote.origin.url | sed -E 's#.*[:/]([^/]+/[^/]+)\.git#\1#')

cat > "$TARGET" <<EOF
// Auto-generated by Snapgate. Do not edit.
export const SNAPGATE = {
  name: "$NAME",
  version: "$VERSION",
  commit: "$HEAD_SHORT",
  fullSha: "$HEAD_FULL",
  commitDate: "$HEAD_DATE",
  repository: "$REPO"
}

console.log(
  "[SNAPGATE]",
  "$NAME v$VERSION ($HEAD_SHORT)"
)
EOF

echo "Generated $TARGET"
